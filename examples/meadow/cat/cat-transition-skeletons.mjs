/**
 * @purpose 标注坐站、起跑收步、跳前准备与转身图集的肢体位置
 * @role 过渡姿势的静态观察数据，不驱动图像
 * @deps 四张 cat-*-v1.png 过渡图集的单格像素坐标
 * @gotcha 关节是人工近似；远侧腿由近侧位置偏移作遮挡示意，并非解剖或蒙皮数据
 */
function mark(body, front, rear, tail, farOffset = 8) {
  const other = (points) => points.map(([x, y]) => [x + farOffset, y - 5]);
  return {
    body,
    front: [body[2], ...front],
    rear: [body[0], ...rear],
    tail,
    frontFar: [body[2], ...other(front)],
    rearFar: [body[0], ...other(rear)],
  };
}
