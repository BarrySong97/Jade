export function catSkeleton(motion, time, amplitude) {
  const source = CAT_SKELETONS[motion.sheet][motion.sheet === "idle" ? 0 : motion.frame];
  return Object.fromEntries(
    Object.entries(source).map(([name, points]) => [
      name,
      points.map(([x, y]) =>
        motion.sheet === "idle" && name === "tail"
          ? deformTailPoint(x, y, time, amplitude)
          : [x, y],
      ),
    ]),
  );
}

const CHAINS = [
  ["frontFar", "#b76513", true],
  ["rearFar", "#356bc1", true],
  ["body", "#13746e", false],
  ["tail", "#8951ae", false],
  ["rear", "#2563ba", false],
  ["front", "#c5690c", false],
];

export function drawCatSkeleton(context, motion, transform, time, amplitude, tailOnly) {
  if (!context) return;
  const skeleton = catSkeleton(motion, time, amplitude);
  context.save();
  context.lineCap = "round";
  context.lineJoin = "round";
  for (const [name, color, far] of CHAINS) {
    if (tailOnly && name !== "tail") continue;
    const points = skeleton[name].map((point) => projectCatPoint(point, transform));
    context.globalAlpha = far ? 0.65 : 1;
    context.setLineDash(far ? [4, 4] : []);
    context.beginPath();
    points.forEach(([x, y], i) => (i === 0 ? context.moveTo(x, y) : context.lineTo(x, y)));
    context.strokeStyle = "#fffefb";
    context.lineWidth = far ? 3.5 : 5;
    context.stroke();
    context.strokeStyle = color;
    context.lineWidth = far ? 1.4 : 2.2;
    context.stroke();
    context.setLineDash([]);
    for (const [x, y] of points) {
      context.beginPath();
      context.arc(x, y, far ? 2 : 3, 0, Math.PI * 2);
      context.fillStyle = "#fffefb";
      context.fill();
      context.stroke();
    }
  }
  if (!tailOnly) {
    context.globalAlpha = 1;
    context.font = "11px system-ui, sans-serif";
    context.textBaseline = "bottom";
    for (const [index, text] of [
      [0, "髋"],
      [2, "肩"],
      [3, "头"],
    ]) {
      const [x, y] = projectCatPoint(skeleton.body[index], transform);
      context.strokeStyle = "#fffefb";
      context.lineWidth = 3;
      context.strokeText(text, x + 7, y - 5);
      context.fillStyle = "#13746e";
      context.fillText(text, x + 7, y - 5);
    }
  }
  context.restore();
}
